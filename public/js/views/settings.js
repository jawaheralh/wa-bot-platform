/**
 * ما يظهر منها يتبع ما يراه المستخدم فعلاً.
 *
 * فبندٌ يظهر ثم يُرفض بـ٤٠٣ عند الضغط أسوأ من بندٍ لا يظهر: الأول
 * يجعل المستخدم يظنّ العطل في النظام.
 */
export async function renderSettings(main, available) {
  const allowed = new Set(available.map((v) => v.id));
  allowed.add('account');

  const groups = GROUPS.map((group) => ({
    ...group,
    items: group.items.filter((item) => allowed.has(item.id)),
  })).filter((group) => group.items.length);

  main.innerHTML = `
    <h2>الإعدادات</h2>
    <p class="subtitle">
      ${groups.reduce((n, g) => n + g.items.length, 0)} شاشة · تُضبط مرة عند التأسيس ثم نادراً
    </p>

    ${groups
      .map(
        (group) => `
          <div class="card">
            <h3>${esc(group.title)}</h3>
            <p class="muted" style="margin-top:0">${esc(group.hint)}</p>
            <div class="grid">
              ${group.items
                .map(
                  (item) => `
                    <button class="setting-card" data-view="${item.id}">
                      <strong>${esc(item.label)}</strong>
                      <span>${esc(item.hint)}</span>
                    </button>`,
                )
                .join('')}
            </div>
          </div>`,
      )
      .join('')}

    ${
      state.me.role === 'system'
        ? `<div class="card">
            <h3>شاشات المنصة</h3>
            <p class="muted" style="margin-top:0">لا تخصّ منشأة بعينها — تظهر لك وحدك في الشريط الجانبي.</p>
            <div class="grid">
              <button class="setting-card" data-view="setup">
                <strong>إعداد المنشأة</strong>
                <span>ربط الرقم بـMeta، وفحص ما ينقص هذه المنشأة قبل أن تعمل.</span>
              </button>
              <button class="setting-card" data-view="tenants">
                <strong>كل المنشآت</strong>
                <span>إضافة منشأة جديدة، وبيانات Meta ومفتاح Claude لكلٍّ منها.</span>
              </button>
            </div>
          </div>`
        : ''
    }
  `;
}
